/** 1 секунда · 2–4 секунды · 5–20 секунд. */
function secWord(count: number): string {
  const tens = Math.abs(count) % 100
  if (tens >= 11 && tens <= 14) return 'секунд'
  const ones = Math.abs(count) % 10
  if (ones === 1) return 'секунду'
  if (ones >= 2 && ones <= 4) return 'секунды'
  return 'секунд'
}

