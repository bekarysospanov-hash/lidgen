// PROBE: все тексты, живущие ровно столько, сколько моки вместо сервера.
//
// Собраны в один модуль не для порядка, а потому, что иначе они не исчезают.
// Пока эти строки лежали полями внутри `otpStep`, `offersPage` и `loginPage`,
// сборка с VITE_USE_MOCKS=false оставляла их в бандле: сборщик вырезает
// недостижимый КОД, но не поле объекта-константы, на который есть ссылка.
// Проверено 17.09 — в dist лежала строка «Проба: подойдёт код 1234», хотя
// на экране она уже не показывалась.
//
// Здесь объект целиком стоит под условием, и при прод-сборке `probeVisible`
// становится константой `false`, а вся ветка с текстами — недостижимым кодом,
// который сборщик убирает.
//
// На утилизации (после GATE 2) этот файл удаляется целиком вместе с моками,
// и `grep -rn "PROBE:" src` покажет места, где на него ссылались.

/**
 * Видны ли пробные подсказки. Ровно то же условие, по которому включаются
 * моки (`api/client.ts`): данные ненастоящие — подсказка уместна; появился
 * реальный бэкенд — она исчезает сама, без отдельной правки и без шанса
 * забыть про неё.
 *
 * Связывать с режимом сборки было бы недостаточно: превью для PM собирается
 * как прод, а данные в нём всё те же мок-данные.
 */
export const probeVisible = import.meta.env.VITE_USE_MOCKS !== 'false'

/**
 * Тексты подсказок. `null` в прод-сборке — и это не осторожность, а способ
 * дать сборщику выкинуть строки: тернарник с константным условием он
 * сворачивает целиком.
 *
 * Экраны обращаются к полям через `probeText?.code` — при `null` подсказки
 * просто нет, и отдельная проверка `probeVisible` рядом не нужна.
 */
export const probeText = probeVisible
  ? ({
      /** Экран подтверждения номера: мок принимает одну константу. */
      code: 'Проба: подойдёт код 1234.',

      /**
       * Вход мебельщика. Конкретный номер, а не диапазон: человеку нужно,
       * что ввести, а не описание множества. Остальные шесть перечислены
       * следом — они нужны, только когда проверяют, что заявка ушла нескольким.
       *
       * Экран входа публичный: как только вместо мок-списка появятся
       * настоящие карточки, эта строка выложила бы телефоны семи мебельщиков
       * на открытую страницу.
       */
      phones: 'Проба: войдите номером +7 701 000-00-01, код 1234.',
      phonesMore: 'Другие мастерские — от +7 701 000-00-02 до +7 701 000-00-07.',

      /**
       * Нерабочая ссылка. На пробе заявки живут в памяти вкладки, и человеку
       * надо сказать причину, иначе он решит, что сломана сама ссылка.
       */
      invalidLink:
        'На пробе ссылка живёт, пока открыта вкладка: заявки хранятся в памяти ' +
        'браузера, а не на сервере. Оставьте заявку заново — с настоящим ' +
        'сервером ссылка будет работать всегда.',

      /** Возврат потерянной ссылки: мессенджера нет, показываем ссылку на месте. */
      linkHere: 'Проба: сообщения никуда не уходят — вот ссылка, она бы пришла в мессенджер.',
      linkOpen: 'Открыть предложения',
      linkNone: 'Проба: по этому номеру подтверждённой заявки нет, поэтому отправлять нечего.',
    } as const)
  : null
