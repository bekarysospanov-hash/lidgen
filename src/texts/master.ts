/** 1 пункт · 2–4 пункта · 5 пунктов. */
function pluralItems(count: number): string {
  const tens = Math.abs(count) % 100
  if (tens >= 11 && tens <= 14) return 'пунктов'
  const ones = Math.abs(count) % 10
  if (ones === 1) return 'пункт'
  if (ones >= 2 && ones <= 4) return 'пункта'
  return 'пунктов'
}

