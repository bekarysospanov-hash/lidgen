/**
 * Когда заявка пришла. Сегодня и вчера называются словом: мебельщик смотрит
 * список по нескольку раз в день, и «сегодня, 14:20» он понимает быстрее,
 * чем «16.09, 14:20». Дальше — дата, время уже не нужно.
 */
export function routedAtLabel(iso: string, now: Date = new Date()): string {
  const at = new Date(iso)
  const time = at.toLocaleTimeString('ru-RU', { hour: '2-digit', minute: '2-digit' })
  const sameDay = (a: Date, b: Date) => a.toDateString() === b.toDateString()

  const yesterday = new Date(now)
  yesterday.setDate(now.getDate() - 1)

  if (sameDay(at, now)) return `сегодня, ${time}`
  if (sameDay(at, yesterday)) return `вчера, ${time}`
  return at.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' })
}

