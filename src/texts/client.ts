/**
 * US-29 — свои заявки. Экран появился 20.09, когда продукт стал
 * маркетплейсом: до этого заявка открывалась только по ссылке из сообщения.
 * Ссылка остаётся главным путём — кабинет её не отменяет.
 */
export const myRequestsPage = {
  label: 'Ваш кабинет',
  title: 'Мои заявки',
  loading: 'Открываем ваши заявки',
  /** Сколько заявок. Число названо: молча укороченный список читают как весь. */
  listTitle: (count: number) => `${count} ${requestWord(count)}`,
  /** Размер не назвали — законный случай (US-05a), а не пропуск. */
  sizeUnknown: 'размер не назван',
  /**
   * Сколько предложений пришло — то, ради чего человек открыл экран.
   * Ноль говорится словами: пустое место он прочитает как сбой.
   */
  quotes: (count: number) => `${count} ${quoteWord(count)}`,
  noQuotes: 'Предложений пока нет',
  open: 'Открыть заявку',
  signOut: 'Выйти',
  /**
   * Пустой кабинет. Не ошибка: человек вошёл, но ещё ничего не заказывал —
   * и такое бывает у того, кто пришёл из каталога и вошёл из любопытства.
   */
  emptyTitle: 'Заявок пока нет',
  emptyBody:
    'Здесь появятся ваши заявки и предложения по ним. Опишите задачу один раз — ' +
    'цену и срок назовут несколько мастерских.',
  toRequest: 'Оставить заявку',
  failedTitle: 'Не получилось открыть заявки',
  retry: 'Попробовать ещё раз',
} as const

/** 1 заявка · 2–4 заявки · 5–20 заявок. */
function requestWord(count: number): string {
  const tens = Math.abs(count) % 100
  if (tens >= 11 && tens <= 14) return 'заявок'
  const ones = Math.abs(count) % 10
  if (ones === 1) return 'заявка'
  if (ones >= 2 && ones <= 4) return 'заявки'
  return 'заявок'
}

/** 1 предложение · 2–4 предложения · 5–20 предложений. */
function quoteWord(count: number): string {
  const tens = Math.abs(count) % 100
  if (tens >= 11 && tens <= 14) return 'предложений'
  const ones = Math.abs(count) % 10
  if (ones === 1) return 'предложение'
  if (ones >= 2 && ones <= 4) return 'предложения'
  return 'предложений'
}
