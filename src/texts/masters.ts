/** 1 мастерская · 2–4 мастерские · 5–20 мастерских. */
function masterWord(count: number): string {
  const tens = Math.abs(count) % 100
  if (tens >= 11 && tens <= 14) return 'мастерских'
  const ones = Math.abs(count) % 10
  if (ones === 1) return 'мастерская'
  if (ones >= 2 && ones <= 4) return 'мастерские'
  return 'мастерских'
}

/** 1 год · 2–4 года · 5–20 лет. */
function yearWord(count: number): string {
  const tens = Math.abs(count) % 100
  if (tens >= 11 && tens <= 14) return 'лет'
  const ones = Math.abs(count) % 10
  if (ones === 1) return 'год'
  if (ones >= 2 && ones <= 4) return 'года'
  return 'лет'
}
