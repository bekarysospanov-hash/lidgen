// §5в — вход и сессия. Одна дверь на обе роли (решение PM 20.09, разбор
// архитектуры того же дня).
//
// Почему одна. Продукт стал маркетплейсом, а в маркетплейсе «Войти» одно:
// человек не должен знать заранее, в какую дверь он стучится. До этого
// дверей было две — /master с отдельной парой операций и токен-ссылка
// у заказчицы, — и мебельщик, заказавший себе шкаф, попадал в тупик:
// сервер выбирал за него одну роль из двух.
//
// Роль не спрашивается у человека и не решается фронтом. Сервер сверяет
// подтверждённый номер с реестром мастерских и отдаёт набор ролей. Отсюда
// же берётся защита от перебора: шаг запроса кода отвечает одинаково
// любому номеру, и «есть ли такой мебельщик» узнаёт только тот, кто владеет
// телефоном и ввёл код.
//
// Чего эта сессия НЕ заменяет: токен заявки (§3). Он остаётся ключом
// «по владению строкой» — по нему заявку открывает и гость, и муж, которому
// переслали ссылку (US-21), и сессии у них нет и не будет. Кабинет —
// второй путь к тем же данным, а не замена первому.
import { z } from 'zod'
import { Iso, OtpCode, Phone, Token } from './primitives'
import { Consent } from './request'
import { MasterProfile } from './master'

/**
 * Роли одной сессии. `client` есть у каждого, кто подтвердил номер:
 * заказать мебель может кто угодно. `master` появляется, только если
 * номер найден в реестре мастерских.
 *
 * Роль выводится сервером при каждом вызове кабинета, а не берётся
 * из снимка в сессии: у мастерской, снятой с публикации, доступ обязан
 * пропасть немедленно, а не через двенадцать часов.
 */
export const SessionRole = z.enum(['client', 'master'])
export type SessionRole = z.infer<typeof SessionRole>

/**
 * Ответ authConfirmCode: кто вошёл, чем авторизуется дальше и до каких пор.
 *
 * `master` непустой тогда и только тогда, когда `master` есть в ролях —
 * это та мастерская, под которой человек отвечает. Срок считает сервер
 * и отдаёт готовым: фронт, вычисляющий «двенадцать часов от сейчас»,
 * разойдётся с сервером на первом же переводе часов.
 */
export const Session = z.object({
  token: Token,
  roles: z.array(SessionRole).min(1),
  expiresAt: Iso,
  master: MasterProfile.nullable(),
})
export type Session = z.infer<typeof Session>

/**
 * Вход authRequestCode. Согласие спрашивается здесь, а не только на заявке:
 * человек может войти, не оставив ни одной, — и тогда у продукта появился
 * бы телефон без записи о правовом основании (US-11, спека §8).
 */
export const AuthRequestCodeInput = z.object({ phone: Phone, consent: Consent })
export type AuthRequestCodeInput = z.infer<typeof AuthRequestCodeInput>

/** Вход authConfirmCode: номер и код из сообщения. Пароля нет нигде. */
export const AuthConfirmCodeInput = z.object({ phone: Phone, code: OtpCode })
export type AuthConfirmCodeInput = z.infer<typeof AuthConfirmCodeInput>
