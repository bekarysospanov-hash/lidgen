// Поле телефона. Наружу отдаёт только десять национальных цифр — собрать
// из них +7XXXXXXXXXX (формат контракта, Phone) может вызывающий экран.
// Маска +7 (___) ___-__-__ живёт в placeholder, а введённое форматируется
// по мере набора: дорисовывать подчёркивания внутрь значения нельзя —
// каретка начинает прыгать, а человек вводит номер один раз и на телефоне.
//
// Разбор и показ вынесены чистыми функциями и покрыты phone.test.ts:
// поле управляемое, значение ходит по кругу «показ → разбор → значение»,
// и этот круг обязан быть тождественным. Один раз он таким не был.

/** Постоянная часть перед номером. Её цифра в разбор попадать не должна. */
export const PHONE_PREFIX = '+7'

/** Маска целиком — она же подсказка в пустом поле. */
export const PHONE_MASK = `${PHONE_PREFIX} (___) ___-__-__`

/** Сколько цифр ждём после кода страны. */
export const PHONE_DIGITS = 10

/**
 * Номер из контракта (`+7XXXXXXXXXX`) → то, как его читают глазами.
 *
 * Заведено 21.09: телефон показывался сырой строкой в трёх местах сразу —
 * на карточке мастерской, в предложении заказчице и в кабинете мебельщика
 * после отправки КП. «+77071234567» человек читает по одной цифре, а его
 * переписывают в трубку и диктуют вслух.
 *
 * Функция одна на все три места намеренно: три собственных форматирования
 * разошлись бы через неделю. В `href="tel:"` при этом уходит формат
 * контракта, а не этот.
 */
export function show(phone: string): string {
  return format(phone.replace(/\D/g, '').replace(/^7/, ''))
}

/** Цифры → то, что видно в поле. Незаполненный хвост просто не рисуется. */
export function format(digits: string): string {
  if (digits.length === 0) return ''
  let out = `${PHONE_PREFIX} (${digits.slice(0, 3)}`
  if (digits.length >= 3) out += ')'
  if (digits.length > 3) out += ` ${digits.slice(3, 6)}`
  if (digits.length > 6) out += `-${digits.slice(6, 8)}`
  if (digits.length > 8) out += `-${digits.slice(8, 10)}`
  return out
}

/**
 * Предыдущее значение + то, что оказалось в поле → новое значение.
 *
 * Разбор обязан быть обратным показу: значение ходит по кругу
 * «значение → format → поле → nextValue → значение», и любая цифра,
 * добавленная показом, вернётся обратно как цифра номера.
 */
export function nextValue(previous: string, raw: string): string {
  // Префикс срезается ДО подсчёта цифр: иначе его семёрка неотличима
  // от цифр номера и подмешивается в значение на каждом нажатии.
  const body = raw.startsWith(PHONE_PREFIX) ? raw.slice(PHONE_PREFIX.length) : raw
  let digits = body.replace(/\D/g, '')

  // Номер Казахстана всегда начинается с семёрки, поэтому ведущая
  // восьмёрка — междугородний префикс, другой трактовки у неё нет.
  if (digits.startsWith('8')) digits = digits.slice(1)

  // Backspace по разделителю: строка стала короче, а цифры те же —
  // значит стёрли скобку или дефис. Убираем цифру, иначе поле «залипает».
  // Условие узкое намеренно: «строка короче» бывает и при вставке поверх
  // выделенного, а это не Backspace. Backspace даёт ровно показанное
  // значение без последнего символа — и ничего другого.
  if (raw === format(previous).slice(0, -1) && digits === previous) {
    return digits.slice(0, -1)
  }

  // Одиннадцать цифр — неразрешимая неоднозначность: это вставленный номер
  // с кодом страны или лишняя цифра, ткнутая в уже набранный. Строка их не
  // различает, поэтому правило выбирает не «угадать», а где ошибаться.
  //
  // Код страны срезается только у свежего ввода — когда в поле пришла строка
  // без нашего префикса, то есть его набрали или вставили целиком. Правка уже
  // набранного всегда режется с хвоста: там лишняя цифра и есть.
  const fresh = !raw.startsWith(PHONE_PREFIX)
  if (fresh && digits.length === PHONE_DIGITS + 1 && digits.startsWith('7')) {
    digits = digits.slice(1)
  }
  return digits.slice(0, PHONE_DIGITS)
}
