/**
 * Роль мастерской: кто делает заказ. Разделение взято из бенчмарка (18.09) —
 * от студии с подрядом и от своего производства заказчик ждёт разного
 * по срокам и по тому, кто приедет на замер.
 *
 * Формулировки правлены 18.09 по замечанию PM: «небольшой цех» — про размер,
 * и так о себе не говорят, когда продают. Роль называет не масштаб,
 * а то, своими ли руками делается заказ.
 *
 * От третьего лица для карточки, от первого для кабинета: заказчик читает
 * «Своя мастерская», мебельщик отмечает «Своя мастерская — делаем сами».
 */
export interface RoleText {
  id: MasterRole
  /** Как читает заказчик. */
  label: string
  hint: string
  /** Как выбирает мебельщик. */
  ownLabel: string
}

