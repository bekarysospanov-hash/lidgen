// ЯДРО ПРОБЫ, как и categories.ts: это формулировки, которыми мастерская
// рассказывает о себе, а заказчик её выбирает. Они переживают эксперимент.
//
// Правило то же (спека §3): человеческий язык, данные — вытягиваем. Слова
// цеха запрещены и здесь: не «монтаж корпусной мебели», а «сборка и установка».
//
// Откуда взят список. Восемь услуг — то, что мебельщик на заказ называет сам,
// когда его спрашивают «что входит»: замер, проект, доставка, сборка,
// демонтаж старого, техника, оплата частями, нестандарт. Всё остальное,
// что встречается в объявлениях, — либо не услуга, а материал (запрещено
// показывать заказчику), либо редкость, которой место в «чём отличаемся»
// своими словами.
import type { MasterService } from '../contract'

export interface ServiceText {
  id: MasterService
  /** Как это называется для заказчика. */
  label: string
  /** Чем это для него оборачивается. Пустая строка — подсказки нет. */
  hint: string
  /** Как мебельщик читает этот же пункт у себя в кабинете. */
  ownLabel: string
}

