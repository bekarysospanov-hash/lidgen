const byId = new Map(services.map((item) => [item.id, item]))

export function serviceText(id: MasterService): ServiceText {
  const found = byId.get(id)
  // Список закрыт схемой: сюда попадает только то, что она пропустила.
  if (found === undefined) throw new Error(`Неизвестная услуга: ${id}`)
  return found
}

