/**
 * Части предмета по категориям. Порядок — как человек собирает предмет
 * в голове: сначала то, из чего он состоит, потом то, что к нему прилагается.
 *
 * Набор под категорию — вопрос формы, а не договора (§2 контракта): сервер
 * принимает любую позицию перечня, и мебельщик, отметивший «Замер» в заявке
 * на шкаф, ошибки не совершает.
 */
const partsByCategory: Record<CategoryId, QuoteItem[]> = {
  kitchen: ['countertop', 'sink', 'appliances', 'softClose', 'lighting'],
  wardrobe: ['mirror', 'lighting', 'softClose'],
  bathroom: ['countertop', 'basin', 'mirror', 'lighting'],
  other: ['countertop', 'lighting', 'softClose'],
}

/** Позиции, предлагаемые в форме: части предмета, затем работы. */
export function compositionFor(category: CategoryId): { parts: QuoteItem[]; services: QuoteItem[] } {
  return { parts: partsByCategory[category], services: compositionServices }
}

/**
 * Отмеченный состав, разложенный на две группы — то, из чего состоит предмет,
 * и работы. Порядок внутри групп берётся из перечня системы, а не из того,
 * как отмечал мебельщик: иначе один и тот же состав читался бы по-разному
 * в двух предложениях, и сравнить их глазами стало бы труднее.
 *
 * Группы нужны не для красоты: позиций до девятнадцати, а список длиннее
 * восьми строк DESIGN.md запрещает — линии сливаются в штриховку, и глазу
 * не за что зацепиться. Обе группы в пределе: частей не больше восьми,
 * работ четыре.
 */
export function splitComposition(items: readonly QuoteItem[]): {
  parts: QuoteItem[]
  services: QuoteItem[]
} {
  const order = Object.keys(compositionLabels) as QuoteItem[]
  const chosen = order.filter((item) => items.includes(item))
  return {
    parts: chosen.filter((item) => !compositionServices.includes(item)),
    services: chosen.filter((item) => compositionServices.includes(item)),
  }
}

