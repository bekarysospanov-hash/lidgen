/**
 * Склонение «метра» по числу из поля. Берёт строку как есть: в поле вводят
 * через запятую, и дробная запись — самостоятельное правило, а не следствие
 * значения. Дробное число ВСЕГДА берёт родительный единственного:
 * «0,5 метра», «3,2 метра», «10,0 метра». Целые — по обычному правилу:
 * 1 метр · 2–4 метра · 5–20 метров · 21 метр · 22 метра · 25 метров.
 * Пустое и нечисловое — множественное: нейтральная подпись у пустого поля.
 */
export function metersUnit(value: string | number): string {
  const raw = String(value).trim().replace(',', '.')
  if (raw.length === 0 || !Number.isFinite(Number(raw))) return mainSize.unitMany
  if (raw.includes('.')) return mainSize.unitFew
  const n = Math.abs(Math.trunc(Number(raw)))
  const tens = n % 100
  if (tens >= 11 && tens <= 14) return mainSize.unitMany
  const ones = n % 10
  if (ones === 1) return mainSize.unitOne
  if (ones >= 2 && ones <= 4) return mainSize.unitFew
  return mainSize.unitMany
}

