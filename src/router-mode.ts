// Где живёт единственная проверка режима роутера. Раньше она стояла только
// в main.tsx, и страница «заявка принята» о ней не знала: ссылка на
// предложения собиралась как origin + /offers/<token> и на статическом
// хостинге вела в никуда — сервера, который отдаст произвольный путь, там нет.
//
// PROBE по происхождению, но снимать вместе с оболочкой нечего: на своём
// домене с настоящим сервером флаг просто не выставляется, и ветка с хешем
// не исполняется.
export const HASH_ROUTER = import.meta.env.VITE_HASH_ROUTER === 'true'

/**
 * Абсолютный адрес страницы приложения — тот, который человек перешлёт
 * мужу в мессенджер. На хеш-роутере путь уезжает за решётку, а база берётся
 * из текущего адреса: артефакт превью лежит не в корне домена.
 */
export function absoluteUrl(path: string): string {
  if (!HASH_ROUTER) return `${window.location.origin}${path}`
  const base = `${window.location.origin}${window.location.pathname}`.replace(/\/+$/, '')
  return `${base}#${path}`
}
