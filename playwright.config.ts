// Сквозной путь заявки — единственный автотест интерфейса в проекте.
//
// Решение PM от 15.09 «DOM-тестов нет» остаётся в силе: тестов на компоненты
// и состояния экранов здесь не будет. Этот файл закрепляет ОДИН сценарий
// целиком — тот, который всё равно проходится руками перед каждым показом.
// Причина конкретная: прогон в 26 шагов, написанный 17.09 скриптом в консоли
// браузера, отработал и исчез вместе с сессией.
import { defineConfig, devices } from '@playwright/test'

/**
 * Свой порт, отличный от дев-сервера харнесса (5173 и автоподбор): тест
 * должен подниматься рядом с открытым превью, не отбирая у него порт.
 */
const PORT = 5199
const BASE = `http://localhost:${PORT}`

export default defineConfig({
  testDir: './e2e',
  // Путь длинный и с мок-задержками; торопиться ему некуда.
  timeout: 120_000,
  // Один прогон, без параллели: мок держит состояние в памяти вкладки,
  // и два сценария разом делили бы одни и те же заявки.
  workers: 1,
  fullyParallel: false,
  reporter: [['list']],
  use: {
    baseURL: BASE,
    // Телефон — основной сценарий: заказчица заполняет форму с него,
    // мебельщик отвечает между цехом и замером. Android, а не iPhone:
    // он ближе к рынку РК и работает на Chromium, который уже установлен —
    // WebKit тянул бы ещё сотню мегабайт ради той же проверки.
    ...devices['Pixel 5'],
    // Снимок и трасса только при падении: разбираться приходится редко,
    // а место они занимают всегда.
    screenshot: 'only-on-failure',
    trace: 'retain-on-failure',
  },
  webServer: {
    command: `npm run dev -- --port ${PORT} --strictPort`,
    url: BASE,
    reuseExistingServer: true,
    timeout: 60_000,
  },
})
